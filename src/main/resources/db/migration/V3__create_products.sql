CREATE TABLE products (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled             BOOLEAN       NOT NULL DEFAULT FALSE,
    name                VARCHAR(150)  NOT NULL,
    slug                VARCHAR(150)  NOT NULL,
    use_in_menu         BOOLEAN       NOT NULL DEFAULT FALSE,
    stock               INTEGER       NOT NULL DEFAULT 0,
    description         VARCHAR(1000),
    price               NUMERIC(10,2) NOT NULL,
    price_with_discount NUMERIC(10,2) NOT NULL,
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_products_slug UNIQUE (slug),
    CONSTRAINT ck_products_stock CHECK (stock >= 0),
    CONSTRAINT ck_products_price CHECK (price >= 0 AND price_with_discount >= 0)
);

CREATE INDEX idx_products_price ON products (price);  -- filtro price-range
