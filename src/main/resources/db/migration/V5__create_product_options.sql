CREATE TABLE product_options (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  INTEGER      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    title       VARCHAR(100) NOT NULL,
    shape       VARCHAR(10)  NOT NULL DEFAULT 'square',
    radius      INTEGER      NOT NULL DEFAULT 0,
    type        VARCHAR(10)  NOT NULL DEFAULT 'text',
    "values"    VARCHAR(255) NOT NULL,  -- palavra reservada: sempre entre aspas
    CONSTRAINT ck_product_options_shape  CHECK (shape IN ('square', 'circle')),
    CONSTRAINT ck_product_options_type   CHECK (type  IN ('text', 'color')),
    CONSTRAINT ck_product_options_radius CHECK (radius >= 0)
);

CREATE INDEX idx_product_options_product_id ON product_options (product_id);
